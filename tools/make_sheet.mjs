import fs from 'node:fs';
import path from 'node:path';
import { Surface } from '../src/core/raster.js';
import { photoSurface } from '../src/core/photo.js';

const dir = 'art/hero';
const files = fs.readdirSync(dir).filter((f) => /\.jpg$/i.test(f)).sort();
const COLS = 4, CELL_W = 320, PAD = 8;
const chunks = [];
for (let i = 0; i < files.length; i += 12) chunks.push(files.slice(i, i + 12));

chunks.forEach((chunk, ci) => {
  const rows = Math.ceil(chunk.length / COLS);
  const cellH = Math.round(CELL_W * 1376 / 768);
  const W = COLS * (CELL_W + PAD) + PAD;
  const H = rows * (cellH + PAD + 22) + PAD;
  const sheet = new Surface(W, H);
  sheet.fill([18, 18, 24]);
  chunk.forEach((f, i) => {
    const name = f.replace(/\.jpg$/, '');
    const img = photoSurface(name);
    const col = i % COLS, row = Math.floor(i / COLS);
    const x = PAD + col * (CELL_W + PAD), y = PAD + row * (cellH + PAD + 22);
    if (img) {
      const h = CELL_W * img.h / img.w;
      const sc = img.scaled(CELL_W, Math.round(h));
      sheet.composite(sc, x, y, 1, 'over');
    }
    // 编号
    const label = String(i + 1 + ci * 12) + ' ' + name;
    drawLabel(sheet, label, x + 4, y + cellH + 4);
  });
  const out = `out/sheets/sheet${ci}.png`;
  fs.mkdirSync('out/sheets', { recursive: true });
  fs.writeFileSync(out, sheet.toPNG());
  console.log(out, chunk.length, 'cells');
});

